#![allow(dead_code)]
//! RNA dinucleotide stacking energy matrices (DSM)
//!
//! Tables encode nearest-neighbor thermodynamic parameters for RNA-RNA interactions.
//! Energy values are in 0.01 kcal/mol (divide by -100 for kcal/mol).
//!
//! Indices: `[q1][q2][t1][t2]` = stacking energy for:
//! ```text
//! Query:  5'─ q1 ─ q2 ─ 3'
//!             |    |
//! Target: 3'─ t1 ─ t2 ─ 5'
//! ```

use crate::config::Matrix;
use crate::dsm_extend::DSM_EXTEND_FLAT;
use crate::types::{Base, BASE_COUNT};

/// DSM table type: 4D array [q1][q2][t1][t2]
pub(crate) type DsmTable = [[[[i16; BASE_COUNT]; BASE_COUNT]; BASE_COUNT]; BASE_COUNT];

/// Number of entries in a flattened DSM table (6^4 = 1296).
pub(crate) const DSM_FLAT_SIZE: usize = BASE_COUNT * BASE_COUNT * BASE_COUNT * BASE_COUNT;

/// Gap index used for DSM lookups (linked to Base::Gap).
pub use crate::types::GAP;

// =============================================================================
// SCORING MODEL - Direction-agnostic penalty-adjusted lookup table
// =============================================================================

/// Penalty-adjusted flat DSM table for one orientation.
///
/// Each instance is one canonical orientation (right or left).
/// Use `transpose()` to create the other orientation.
#[derive(Clone, Debug)]
pub struct ScoringModel {
    table: [i32; DSM_FLAT_SIZE],
    pair_mat: [[u8; 6]; 6],
}

impl ScoringModel {
    /// Create a new scoring table from a base matrix, baking in the extension penalty.
    pub fn new(matrix: Matrix, penalty: i32, allow_wobble: bool) -> Self {
        let source_table = match matrix {
            Matrix::T04 => &T04,
            Matrix::T99 => &T99,
        };

        // The legacy matrices use the old Base ordering: A=1, G=2, C=3, U=4, N=5.
        // Our new Base order is: A=1, C=2, G=3, N=4, U=5.
        // This array maps our new index -> legacy matrix index.
        let new_to_legacy = [0, 1, 3, 2, 5, 4];

        let mut table = [0i32; DSM_FLAT_SIZE];
        for q1 in 0..6 {
            for q2 in 0..6 {
                for t1 in 0..6 {
                    for t2 in 0..6 {
                        let t1_orig = Base::from_idx(t1).complement().idx();
                        let t2_orig = Base::from_idx(t2).complement().idx();
                        
                        let idx = q1 * 216 + q2 * 36 + t1 * 6 + t2;

                        let l_q1 = new_to_legacy[q1];
                        let l_q2 = new_to_legacy[q2];
                        let l_t1_orig = new_to_legacy[t1_orig];
                        let l_t2_orig = new_to_legacy[t2_orig];
                        
                        let orig_idx = l_q1 * 216 + l_q2 * 36 + l_t1_orig * 6 + l_t2_orig;
                        
                        table[idx] =
                            source_table[l_q1][l_q2][l_t1_orig][l_t2_orig] as i32 - penalty * DSM_EXTEND_FLAT[orig_idx];
                    }
                }
            }
        }

        let source_pair_mat = if allow_wobble {
            &PAIR_MAT
        } else {
            &PAIR_MAT_NO_GU
        };

        let mut pair_mat = [[0u8; 6]; 6];
        for q in 0..6 {
            for t in 0..6 {
                let t_orig = Base::from_idx(t).complement().idx();
                pair_mat[q][t] = source_pair_mat[new_to_legacy[q]][new_to_legacy[t_orig]];
            }
        }

        Self { table, pair_mat }
    }

    /// Produce a left-canonical (transposed) copy: `[q1][q2][t1][t2] → [q2][q1][t2][t1]`.
    pub fn transpose(&self) -> ScoringModel {
        let mut table = [0i32; DSM_FLAT_SIZE];
        for q1 in 0..6 {
            for q2 in 0..6 {
                for t1 in 0..6 {
                    for t2 in 0..6 {
                        let dst = q1 * 216 + q2 * 36 + t1 * 6 + t2;
                        let src = q2 * 216 + q1 * 36 + t2 * 6 + t1;
                        table[dst] = self.table[src];
                    }
                }
            }
        }
        Self {
            table,
            pair_mat: self.pair_mat,
        }
    }

    /// Point query for dinucleotide stacking energy.
    #[inline(always)]
    pub fn lookup(&self, q1: usize, q2: usize, t1: usize, t2: usize) -> i32 {
        debug_assert!(q1 < 6 && q2 < 6 && t1 < 6 && t2 < 6);
        let idx = q1 * 216 + q2 * 36 + t1 * 6 + t2;
        // SAFETY: All args ∈ 0..6. Max idx = 5*216+5*36+5*6+5 = 1295 < 1296.
        unsafe { *self.table.get_unchecked(idx) }
    }

    /// Check if two bases form a valid pair.
    #[inline(always)]
    pub fn is_pair(&self, q: Base, t: Base) -> bool {
        let (qi, ti) = (q.idx(), t.idx());
        debug_assert!(qi < 6 && ti < 6);
        // SAFETY: Base::idx() returns 0..6, matching the 6×6 pair_mat dimensions.
        unsafe { *self.pair_mat.get_unchecked(qi).get_unchecked(ti) != 0 }
    }

    /// Seed energy calculation with antiparallel indexing.
    pub fn seed_energy(
        &self,
        query: &[Base],
        target: &[Base],
        q_pos: usize,
        t_pos: usize,
        len: usize,
    ) -> i32 {
        if len <= 1 {
            return 0;
        }
        let mut score = 0;
        let t_match_end = t_pos + len - 1;
        for i in 0..(len - 1) {
            score += self.lookup(
                query[q_pos + i].idx(),
                query[q_pos + i + 1].idx(),
                target[t_match_end - i].idx(),
                target[t_match_end - i - 1].idx(),
            );
        }
        score
    }
}


