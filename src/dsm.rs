#![allow(dead_code)]
//! RNA dinucleotide stacking energy matrices (DSM)
//!
//! Tables encode nearest-neighbor thermodynamic parameters for RNA-RNA interactions.
//! Energy values are in 0.01 kcal/mol (divide by -100 for kcal/mol).
//!
//! Indices: `[q1][q2][t1][t2]` = stacking energy for:
//! ```text
//! Query:  5'─ q1 ─ q2 ─ 3'
//!             |    |
//! Target: 3'─ t1 ─ t2 ─ 5'
//! ```

use crate::types::{BASE_COUNT, Base};

/// DSM table type: 4D array [q1][q2][t1][t2]
pub type DsmTable = [[[[i16; BASE_COUNT]; BASE_COUNT]; BASE_COUNT]; BASE_COUNT];

/// Type-safe DSM table accessor
#[derive(Debug)]
pub struct Dsm(pub &'static DsmTable);

impl Dsm {
    /// Turner 2004 parameters (positive strand)
    pub const T04: Self = Self(&DSM_T04_POS);

    pub fn get(&self, q1: Base, q2: Base, t1: Base, t2: Base) -> i16 {
        self.0[q1.idx()][q2.idx()][t1.idx()][t2.idx()]
    }
}

/// Flattened DSM table for single-lookup access.
/// Index = q1*216 + q2*36 + t1*6 + t2 where each dim is 0..6.
static DSM_FLAT: [i32; 1296] = {
    let mut flat = [0i32; 1296];
    let mut q1 = 0;
    while q1 < 6 {
        let mut q2 = 0;
        while q2 < 6 {
            let mut t1 = 0;
            while t1 < 6 {
                let mut t2 = 0;
                while t2 < 6 {
                    let idx = q1 * 216 + q2 * 36 + t1 * 6 + t2;
                    flat[idx] = DSM_T04_POS[q1][q2][t1][t2] as i32;
                    t2 += 1;
                }
                t1 += 1;
            }
            q2 += 1;
        }
        q1 += 1;
    }
    flat
};

/// Raw DSM lookup function for hot path DP.
/// Single flat array access - faster than 4 nested lookups.
#[inline(always)]
pub fn dsm_lookup_raw(q1: usize, q2: usize, t1: usize, t2: usize) -> i32 {
    // Safety: Indices are guaranteed < 6 by caller logic (Base::idx())
    // Single lookup: q1*216 + q2*36 + t1*6 + t2
    let idx = q1 * 216 + q2 * 36 + t1 * 6 + t2;
    unsafe { *DSM_FLAT.get_unchecked(idx) }
}

/// Represents a stacked base pair for energy calculation.
///
/// Encapsulates the biological meaning of a dinucleotide stack:
/// ```text
///   5' [q1]-[q2] 3'   Query strand
///       |    |
///   3' [t1]-[t2] 5'   Target strand (antiparallel)
/// ```
///
/// The complement transformation is applied internally when creating
/// from bases, centralizing the antiparallel binding semantics.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct StackPair {
    /// Query 5' base
    pub q1: Base,
    /// Query 3' base  
    pub q2: Base,
    /// Target 3' base (pairs with q1)
    pub t1: Base,
    /// Target 5' base (pairs with q2)
    pub t2: Base,
}

impl StackPair {
    /// Create from bases directly (no transformation).
    #[inline]
    pub fn new(q1: Base, q2: Base, t1: Base, t2: Base) -> Self {
        Self { q1, q2, t1, t2 }
    }

    /// Create from bases, applying complement to target.
    ///
    /// This is the standard way to create a StackPair for energy calculation.
    /// The complement transformation handles the antiparallel binding semantics:
    /// when target base T pairs with query base Q, we need complement(T) for DSM lookup.
    #[inline]
    pub fn from_bases_complemented(q1: Base, q2: Base, t1: Base, t2: Base) -> Self {
        Self {
            q1,
            q2,
            t1: t1.complement(),
            t2: t2.complement(),
        }
    }

    /// Get stacking energy from T04 matrix (default).
    #[inline]
    pub fn energy(&self) -> i16 {
        Dsm::T04.get(self.q1, self.q2, self.t1, self.t2)
    }

    /// Get energy from a specific DSM table.
    #[inline]
    pub fn energy_with(&self, dsm: &Dsm) -> i16 {
        dsm.get(self.q1, self.q2, self.t1, self.t2)
    }
}

