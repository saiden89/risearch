#![allow(dead_code)]
//! RNA dinucleotide stacking energy matrices (DSM)
//!
//! Tables encode nearest-neighbor thermodynamic parameters for RNA-RNA interactions.
//! Energy values are in 0.01 kcal/mol (divide by -100 for kcal/mol).
//!
//! Indices: `[q1][q2][t1][t2]` = stacking energy for:
//! ```text
//! Query:  5'─ q1 ─ q2 ─ 3'
//!             |    |
//! Target: 3'─ t1 ─ t2 ─ 5'
//! ```

/// Nucleotide/gap representation for DSM indexing
#[repr(u8)]
#[derive(Clone, Copy, Debug, PartialEq, Eq, Default)]
pub enum Base {
    #[default]
    Gap = 0,
    A = 1,
    G = 2,
    C = 3,
    U = 4,
    N = 5,
}

impl Base {
    /// Convert ASCII nucleotide byte to Base enum
    #[inline]
    pub fn from_byte(b: u8) -> Self {
        match b {
            b'A' | b'a' => Base::A,
            b'G' | b'g' => Base::G,
            b'C' | b'c' => Base::C,
            b'U' | b'u' | b'T' | b't' => Base::U,
            _ => Base::N,
        }
    }

    /// Convert to array index
    #[inline]
    pub const fn idx(self) -> usize {
        self as usize
    }

    /// Get standard uppercase ASCII byte (A, G, C, U, N)
    #[inline]
    pub fn to_u8_upper(self) -> u8 {
        match self {
            Base::A => b'A',
            Base::G => b'G',
            Base::C => b'C',
            Base::U => b'U', // Represents U or T
            Base::Gap => b'-',
            Base::N => b'N',
        }
    }

    /// Watson-Crick complement (A <-> U/T, G <-> C)
    #[inline]
    pub fn complement(self) -> Self {
        match self {
            Base::A => Base::U,
            Base::U => Base::A,
            Base::G => Base::C,
            Base::C => Base::G,
            _ => self,
        }
    }

    /// Get fingerprint character for this pair (P=Paired, W=Wobble, U=Unpaired)
    #[inline]
    pub fn pairing_class(self, other: Base) -> char {
        match (self, other) {
            (Base::A, Base::U) | (Base::U, Base::A) | (Base::G, Base::C) | (Base::C, Base::G) => {
                'P'
            } // Watson-Crick
            (Base::G, Base::U) | (Base::U, Base::G) => 'W', // Wobble
            _ => 'U',                                       // Unmatched
        }
    }
}

/// Number of nucleotide types (Gap, A, G, C, U, N)
pub const BASE_COUNT: usize = 6;

/// DSM table type: 4D array [q1][q2][t1][t2]
pub type DsmTable = [[[[i16; BASE_COUNT]; BASE_COUNT]; BASE_COUNT]; BASE_COUNT];

/// Type-safe DSM table accessor
pub struct Dsm(pub &'static DsmTable);

impl Dsm {
    /// Turner 2004 parameters (positive strand)
    pub const T04: Self = Self(&DSM_T04_POS);

    /// Get stacking energy for dinucleotide pair
    #[inline]
    pub fn get(&self, q1: Base, q2: Base, t1: Base, t2: Base) -> i16 {
        self.0[q1.idx()][q2.idx()][t1.idx()][t2.idx()]
    }
}

